"""Builds the Google Fonts index for swift-design-kit from a google/fonts checkout at a pinned commit.

    git init fonts && cd fonts && git remote add origin https://github.com/google/fonts.git
    git sparse-checkout set --no-cone /ofl/ /apache/ /ufl/ && git fetch --depth 1 origin <commit> && git checkout FETCH_HEAD
    python3 Scripts/google-fonts-index.py <checkout> > index.tsv
    swift Scripts/google-fonts-families.swift <checkout> index.tsv > families.tsv
    python3 Scripts/google-fonts-index.py --swift index.tsv families.tsv <commit> > Sources/DesignKit/Templates/GoogleFontIndex.swift

One line per family: family, folder, licence dir, category, axes, files (name:sha256:bytes[:style:weight]),
then (in the Swift file) the family CoreText reads when it differs. Families with no METADATA.pb, a missing
font file or no licence file are left out (reported on stderr).
"""
import hashlib, json, os, re, sys

def build_index():
    root = sys.argv[1]
    out = []
    LIC = {"ofl": ["OFL.txt"], "apache": ["LICENSE.txt"], "ufl": ["UFL.txt", "LICENCE.txt"]}
    CAT = {"SERIF": "serif", "SANS_SERIF": "sans", "DISPLAY": "display", "HANDWRITING": "script", "MONOSPACE": "mono"}

    def parse(text):
        # Just the fields used: name, category (first), fonts{style,weight,filename}, axes{tag,min_value,max_value}.
        name = re.search(r'^name: "(.*)"', text, re.M)
        cats = re.findall(r'^category: "(.*)"', text, re.M)
        fonts = re.findall(r'^fonts \{(.*?)^\}', text, re.M | re.S)
        axes = re.findall(r'^axes \{(.*?)^\}', text, re.M | re.S)
        fl = []
        for f in fonts:
            g = lambda k: (re.search(r'%s: "?([^"\n]*)"?' % k, f) or [None, None])[1]
            fl.append((g("filename"), g("style"), g("weight")))
        al = []
        for a in axes:
            g = lambda k: re.search(r'%s: "?([^"\n]*)"?' % k, a)[1]
            al.append((g("tag"), float(g("min_value")), float(g("max_value"))))
        return (name[1] if name else None), cats, fl, al

    def sha(p):
        h = hashlib.sha256()
        with open(p, "rb") as f:
            for b in iter(lambda: f.read(1 << 20), b""): h.update(b)
        return h.hexdigest()

    def num(x):
        return str(int(x)) if x == int(x) else str(x)

    skipped = []
    for licdir in ("ofl", "apache", "ufl"):
        for folder in sorted(os.listdir(os.path.join(root, licdir))):
            d = os.path.join(root, licdir, folder)
            meta = os.path.join(d, "METADATA.pb")
            if not os.path.isfile(meta):
                skipped.append(folder + ": no METADATA"); continue
            name, cats, fonts, axes = parse(open(meta, encoding="utf-8").read())
            lic = next((l for l in LIC[licdir] if os.path.isfile(os.path.join(d, l))), None)
            if lic is None:
                skipped.append(folder + ": no licence file"); continue
            files = []
            ok = True
            for fn, style, weight in fonts:
                p = os.path.join(d, fn)
                if not os.path.isfile(p):
                    ok = False; skipped.append(folder + ": missing " + fn); break
                files.append("%s:%s:%d:%s:%s" % (fn, sha(p), os.path.getsize(p), "i" if style == "italic" else "n", weight))
            if not ok or not files: continue
            lp = os.path.join(d, lic)
            files.append("%s:%s:%d" % (lic, sha(lp), os.path.getsize(lp)))
            cat = CAT.get(cats[0], "sans") if cats else "sans"
            ax = ",".join("%s:%s:%s" % (t, num(a), num(b)) for t, a, b in axes)
            for field in (name, folder, ax):
                assert "\t" not in field and "\n" not in field
            out.append("\t".join([name, folder, licdir, cat, ax, ";".join(files)]))

    sys.stdout.write("\n".join(out) + "\n")
    sys.stderr.write("%d families, %d skipped\n%s\n" % (len(out), len(skipped), "\n".join(skipped[:40])))


SWIFT_HEADER = '''//
//  GoogleFontIndex.swift
//  DesignKit
//
//  Created by David Sherlock on 2026.
//
//  Every family in the google/fonts repository (ofl/, apache/, ufl/) at one
//  pinned commit, generated by Scripts/google-fonts-index.py from each
//  family's METADATA.pb and its files: the SHA-256 of every font and of its
//  licence file was measured on the files at that commit. One line a family,
//  tab-separated: name, folder, licence folder, category, axes
//  (tag:min:max), files (name:sha256:bytes[:n|i:weight]; the licence last),
//  and the family CoreText reads when it differs from the name. Nothing is
//  bundled; a family is fetched the first time a design names it.
//

extension OpenFonts {

    /// The google/fonts commit every file is fetched from.
    public static let commit = "COMMIT"

    static let index = #"""
'''


if sys.argv[1] == "--swift":
    index = [l.rstrip("\n").split("\t") for l in open(sys.argv[2])]
    drawn = dict(l.rstrip("\n").split("\t") for l in open(sys.argv[3]))
    rows = ["\t".join(r + [drawn[r[1]] if drawn[r[1]] != r[0] else ""]) for r in index]
    sys.stdout.write(SWIFT_HEADER.replace("COMMIT", sys.argv[4]) + "\n".join("    " + r for r in rows) + '\n    """#\n}\n')
else:
    build_index()
