import Foundation

/// Where the block of lines sits in its frame, top to bottom.
public enum VerticalAlign: String, DesignChoice {
    /// At the top of the frame.
    case top
    /// In the middle of the frame.
    case middle
    /// At the bottom of the frame.
    case bottom
}
